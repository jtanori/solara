import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { MakeTime, SiderealTime } from "astronomy-engine";
import { castChart, houseOf } from "../src/lib/chart";
import { BODIES, isRetrograde, longitudeOf, normalize, trueNodeLongitudeWithFallback } from "../src/lib/astro";

/**
 * Independent validation against Swiss Ephemeris (pyswisseph 2.10.03), the reference
 * implementation professional astrological software uses.
 *
 * This is the gate on #102: without it the chart is internally consistent but unproven.
 * The angles and whole-sign cusps are the gate on the *house* half of #101 — Placidus
 * remains the only unpinned piece there.
 *
 * The fixtures were generated by `scripts/gen-ephemeris-fixtures.py` — regenerate them with
 * `python3 -m venv .venv && .venv/bin/pip install pyswisseph && .venv/bin/python
 * scripts/gen-ephemeris-fixtures.py > tests/fixtures/ephemeris.json`. They are committed so
 * CI needs no Python.
 */

type Fixture = {
  id: string;
  note: string;
  birth: string;
  timezone: string;
  castAt: string;
  place: string;
  /** Return-place coordinates the angles belong to. */
  latitude: number;
  longitude: number;
  /** True iff |latitude| >= 66 — the product cutoff where the Ascendant is omitted. */
  polar: boolean;
  source: string;
  bodies: Record<string, { longitude: number; speed: number }>;
  trueNode: number;
  /** Reference sidereal time in degrees (Swiss Ephemeris ARMC). */
  armc: number;
  /** Null exactly on polar cases, with the reason recorded — never absent. */
  ascendant: number | null;
  ascendantOmittedReason?: string;
  midheaven: number;
  /** Whole-sign cusps from the reference; null exactly on polar cases. */
  cusps: number[] | null;
};

const data = JSON.parse(readFileSync("tests/fixtures/ephemeris.json", "utf8")) as {
  ephemeris: string;
  houses: string;
  toleranceDegrees: number;
  cases: Fixture[];
};

const TOLERANCE = data.toleranceDegrees;

function angularError(a: number, b: number): number {
  return Math.abs((((a - b) % 360) + 540) % 360 - 180);
}

test("fixtures are present and carry their provenance", () => {
  assert.ok(data.cases.length >= 7, `expected at least 7 fixtures, got ${data.cases.length}`);
  assert.match(data.ephemeris, /Swiss Ephemeris/, "fixtures must record the ephemeris that produced them");
  for (const fixture of data.cases) {
    assert.ok(fixture.castAt.endsWith("Z"), `${fixture.id}: castAt must be UTC`);
    assert.equal(Object.keys(fixture.bodies).length, 10, `${fixture.id}: all ten bodies`);
  }
});

for (const fixture of data.cases) {
  test(`every body matches Swiss Ephemeris — ${fixture.id} (${fixture.note})`, () => {
    const when = new Date(fixture.castAt);
    const failures: string[] = [];
    for (const body of BODIES) {
      const expected = fixture.bodies[body]?.longitude;
      assert.equal(typeof expected, "number", `${fixture.id}: fixture is missing ${body}`);
      const actual = longitudeOf(body, when);
      const error = angularError(actual, expected!);
      if (error > TOLERANCE) {
        failures.push(`${body}: got ${actual.toFixed(4)} expected ${expected!.toFixed(4)} (${error.toFixed(4)}° off)`);
      }
    }
    assert.deepEqual(failures, [], `${fixture.id} deviates from the reference ephemeris:\n  ${failures.join("\n  ")}`);
  });
}

test("the true node matches Swiss Ephemeris on every fixture", () => {
  const failures: string[] = [];
  for (const fixture of data.cases) {
    const { longitude } = trueNodeLongitudeWithFallback(new Date(fixture.castAt));
    const error = angularError(longitude, fixture.trueNode);
    if (error > TOLERANCE) {
      failures.push(`${fixture.id}: got ${longitude.toFixed(4)} expected ${fixture.trueNode.toFixed(4)} (${error.toFixed(4)}° off)`);
    }
  }
  assert.deepEqual(failures, [], `true node deviates:\n  ${failures.join("\n  ")}`);
});

// ------------------------------------------------------------------ angles + houses

/**
 * Local sidereal time in degrees — the RAMC `castChart` is fed in production by
 * `calculateSolarReturnChart`: apparent Greenwich sidereal time from astronomy-engine,
 * advanced by east-positive longitude. It is asserted against the reference ARMC first,
 * so a sidereal-time error can never be misread as a broken angle formula.
 */
function ramcDegreesAt(at: Date, longitude: number): number {
  return normalize(SiderealTime(MakeTime(at)) * 15 + longitude);
}

/** The chart under test: whole-sign, at the fixture's instant and place. */
function castFixture(fixture: Fixture) {
  const at = new Date(fixture.castAt);
  return castChart({
    at,
    latitude: fixture.latitude,
    longitude: fixture.longitude,
    ramcDegrees: ramcDegreesAt(at, fixture.longitude),
  });
}

test("fixtures record their places, angles and the polar omission explicitly", () => {
  assert.match(data.houses, /Swiss Ephemeris/, "fixtures must record what produced the angles");
  assert.ok(
    data.cases.some(fixture => fixture.polar),
    "the fixture set must contain a polar case — the omission semantics are part of the contract",
  );
  for (const fixture of data.cases) {
    assert.ok(Number.isFinite(fixture.latitude) && Math.abs(fixture.latitude) <= 90, `${fixture.id}: latitude`);
    assert.ok(Number.isFinite(fixture.longitude) && Math.abs(fixture.longitude) <= 180, `${fixture.id}: longitude`);
    assert.ok(Number.isFinite(fixture.armc), `${fixture.id}: reference ARMC`);
    assert.ok(Number.isFinite(fixture.midheaven), `${fixture.id}: reference Midheaven`);
    assert.ok(
      "ascendant" in fixture,
      `${fixture.id}: the Ascendant must be recorded — null at polar latitudes, never absent`,
    );
    assert.equal(fixture.polar, Math.abs(fixture.latitude) >= 66, `${fixture.id}: the polar flag must follow the 66° product cutoff`);
    if (fixture.polar) {
      assert.equal(fixture.ascendant, null, `${fixture.id}: polar fixtures record the missing Ascendant explicitly`);
      assert.ok((fixture.ascendantOmittedReason ?? "").length > 40, `${fixture.id}: the omission must carry its reason`);
      assert.equal(fixture.cusps, null, `${fixture.id}: no cusps without an Ascendant`);
    } else {
      assert.equal(typeof fixture.ascendant, "number", `${fixture.id}: non-polar fixtures record the Ascendant`);
      assert.ok(Array.isArray(fixture.cusps) && fixture.cusps.length === 12, `${fixture.id}: twelve whole-sign cusps`);
      // A cusp comparison is only meaningful when the Ascendant is not within tolerance of
      // a sign boundary — there a 0.05° error flips its sign and changes every cusp. The
      // generator refuses to emit such a fixture; this keeps that promise honest.
      const asc = fixture.ascendant as number;
      const toBoundary = Math.min(asc % 30, 30 - (asc % 30));
      assert.ok(
        toBoundary > TOLERANCE,
        `${fixture.id}: Ascendant ${asc}° is ${toBoundary.toFixed(2)}° from a sign boundary — too close to pin cusps`,
      );
    }
  }
});

test("the Midheaven matches Swiss Ephemeris on every fixture, polar included", () => {
  const failures: string[] = [];
  for (const fixture of data.cases) {
    const at = new Date(fixture.castAt);
    // First link in the chain: the sidereal time itself, against the reference ARMC.
    const ramc = ramcDegreesAt(at, fixture.longitude);
    const ramcError = angularError(ramc, fixture.armc);
    if (ramcError > TOLERANCE) {
      failures.push(`${fixture.id}: sidereal time ${ramc.toFixed(4)}° vs reference ARMC ${fixture.armc.toFixed(4)}° (${ramcError.toFixed(4)}° off)`);
      continue;
    }
    const midheaven = castFixture(fixture).angles.midheaven.longitude;
    const error = angularError(midheaven, fixture.midheaven);
    if (error > TOLERANCE) {
      failures.push(`${fixture.id}: MC ${midheaven.toFixed(4)}° vs reference ${fixture.midheaven.toFixed(4)}° (${error.toFixed(4)}° off)`);
    }
  }
  assert.deepEqual(failures, [], `the Midheaven deviates from the reference:\n  ${failures.join("\n  ")}`);
});

test("the Ascendant matches Swiss Ephemeris on every non-polar fixture", () => {
  const failures: string[] = [];
  for (const fixture of data.cases) {
    if (fixture.polar) continue;
    const ascendant = castFixture(fixture).angles.ascendant;
    assert.equal(typeof ascendant?.longitude, "number", `${fixture.id}: an Ascendant must exist below 66°`);
    const error = angularError(ascendant!.longitude, fixture.ascendant!);
    if (error > TOLERANCE) {
      failures.push(`${fixture.id}: ASC ${ascendant!.longitude.toFixed(4)}° vs reference ${fixture.ascendant!.toFixed(4)}° (${error.toFixed(4)}° off)`);
    }
  }
  assert.deepEqual(failures, [], `the Ascendant deviates from the reference:\n  ${failures.join("\n  ")}`);
});

test("whole-sign cusps are the Ascendant's sign boundaries, exactly as the reference draws them", () => {
  const failures: string[] = [];
  for (const fixture of data.cases) {
    if (fixture.polar) continue;
    assert.ok(Array.isArray(fixture.cusps), `${fixture.id}: reference cusps`);
    const facts = castFixture(fixture);
    assert.ok(facts.angles.ascendant, `${fixture.id}: cusps need an Ascendant`);
    const start = Math.floor(facts.angles.ascendant!.longitude / 30) * 30;
    for (let i = 0; i < 12; i++) {
      const expected = normalize(start + i * 30);
      if (facts.houses[i] !== expected) {
        failures.push(`${fixture.id}: cusp ${i + 1} is ${facts.houses[i]}°, expected ${expected}° (ASC sign start ${start}° + ${i * 30}°)`);
      }
      if (facts.houses[i] !== fixture.cusps![i]) {
        failures.push(`${fixture.id}: cusp ${i + 1} is ${facts.houses[i]}°, Swiss Ephemeris says ${fixture.cusps![i]}°`);
      }
    }
    if (houseOf(facts.angles.ascendant!.longitude, facts.houses) !== 1) {
      failures.push(`${fixture.id}: the Ascendant must fall in house 1`);
    }
  }
  assert.deepEqual(failures, [], `whole-sign cusps deviate:\n  ${failures.join("\n  ")}`);
});

/**
 * Above 66° there is no Ascendant — not "an Ascendant we did not compute", but a point the
 * reference itself cannot name for the whole sidereal day (Swiss Ephemeris flips it 180°
 * part of the time and refuses quadrant houses outright). The fixture records the omission
 * as an explicit null; this test pins that the code agrees, on every axis: no Ascendant, no
 * cusps, no house assignments, a warning for the user — and a Midheaven regardless.
 */
test("at polar latitude the Ascendant is explicitly omitted, and only the Midheaven survives", () => {
  const polar = data.cases.filter(fixture => fixture.polar);
  assert.ok(polar.length > 0, "the fixture set must contain the polar case");
  for (const fixture of polar) {
    const facts = castFixture(fixture);
    assert.equal(facts.angles.ascendant, null, `${fixture.id}: no Ascendant above 66° — the reference records the same omission`);
    assert.deepEqual(facts.houses, [], `${fixture.id}: no houses without an Ascendant`);
    assert.ok(facts.bodies.every(body => body.house === null), `${fixture.id}: no body may claim a house`);
    const error = angularError(facts.angles.midheaven.longitude, fixture.midheaven);
    assert.ok(
      error <= TOLERANCE,
      `${fixture.id}: the Midheaven is latitude-independent — got ${facts.angles.midheaven.longitude.toFixed(4)}°, reference ${fixture.midheaven.toFixed(4)}° (${error.toFixed(4)}° off)`,
    );
    assert.ok(
      facts.warnings.some(warning => warning.includes("high latitude")),
      `${fixture.id}: the omission must be explained to the user, not silent`,
    );
  }
});

/**
 * Every non-luminary body, on every fixture: the retrograde flag must agree with the
 * reference velocity. This is the assertion the first version of this test was pretending
 * to make (it computed `expected` and then never compared it to anything).
 *
 * The comparison is between two *independent* derivations of the same fact:
 * `isRetrograde()` uses a ±6h central difference of its own longitudes, while the fixture
 * `speed` comes from Swiss Ephemeris. Agreement is therefore evidence, not a tautology.
 */
test("retrograde flags agree with the reference velocity on every fixture", () => {
  const failures: string[] = [];
  for (const fixture of data.cases) {
    const when = new Date(fixture.castAt);
    for (const body of BODIES) {
      if (body === "Sun" || body === "Moon") continue; // never retrograde
      const speed = fixture.bodies[body].speed;
      const actual = isRetrograde(body, when);
      if (actual === null) continue; // reported as stationary; see the stationary test below
      const expected = speed < 0;
      if (actual !== expected) {
        failures.push(
          `${fixture.id} ${body}: reference speed ${speed.toFixed(4)}°/day implies ` +
          `retrograde=${expected}, code says ${actual}`,
        );
      }
    }
  }
  assert.deepEqual(failures, [], `retrograde flags disagree with the reference:\n  ${failures.join("\n  ")}`);
});

/**
 * The station window: |motion| < 0.003°/day is reported as `null` rather than a guess, and
 * any body the code calls stationary must genuinely be slow by the reference — otherwise the
 * code is hiding a real direction behind "unknown".
 */
test("a body reported as stationary really is slow in the reference", () => {
  for (const fixture of data.cases) {
    const when = new Date(fixture.castAt);
    for (const body of BODIES) {
      if (body === "Sun" || body === "Moon") continue;
      if (isRetrograde(body, when) !== null) continue;
      const speed = Math.abs(fixture.bodies[body].speed);
      assert.ok(speed < 0.01, `${fixture.id} ${body}: called stationary but reference speed is ${speed.toFixed(4)}°/day`);
    }
  }
});

test("the stationary threshold is consistent with the reference, not arbitrarily low", () => {
  // REGRESSION GUARD for the latent threshold mismatch. `dailyMotion` reports null below
  // 0.003°/day. Any body inside that band must be inside the reference's own "effectively
  // stationary" band too — if a fixture ever contains a body at, say, 0.002°/day that the
  // reference calls retrograde, the two thresholds have drifted apart and this fails.
  const STATIONARY_DEGREES_PER_DAY = 0.003;
  for (const fixture of data.cases) {
    const when = new Date(fixture.castAt);
    for (const body of BODIES) {
      if (body === "Sun" || body === "Moon") continue;
      const speed = fixture.bodies[body].speed;
      if (Math.abs(speed) < STATIONARY_DEGREES_PER_DAY) {
        assert.equal(isRetrograde(body, when), null, `${fixture.id} ${body}: slow in reference, should be null`);
      } else {
        assert.notEqual(isRetrograde(body, when), null, `${fixture.id} ${body}: fast in reference, must not be null`);
      }
    }
  }
});

test("a heliocentric regression cannot silently return", () => {
  // The bug this suite was written for: EclipticLongitude returns *heliocentric* longitude.
  // If a future change reintroduces it, Venus is off by ~47° and Mars by ~19° on this date,
  // far outside tolerance — so this assertion fails loudly rather than shipping.
  const when = new Date("2026-05-16T11:46:50.405Z");
  const venus = longitudeOf("Venus", when);
  assert.ok(angularError(venus, 86.9433) < 0.05, `Venus must be geocentric (86.94°), got ${venus.toFixed(2)}°`);
  const moon = longitudeOf("Moon", when);
  assert.ok(angularError(moon, 50.7498) < 0.05, `Moon must be geocentric (50.75°), got ${moon.toFixed(2)}°`);
});
